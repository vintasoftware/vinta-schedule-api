def build_parser() -> argparse.ArgumentParser:
    """The CLI. Every subcommand is dry-run unless `--execute` is passed."""
    parser = argparse.ArgumentParser(
        prog="resource_directory_spike",
        description=(
            "Probe Google and Microsoft room-directory writes against SANDBOX tenants. "
            "Dry-run by default: nothing is sent without --execute."
        ),
    )
    parser.add_argument("-v", "--verbose", action="store_true", help="debug logging")
    subparsers = parser.add_subparsers(dest="command", required=True, metavar="SUBCOMMAND")

    def add_execute(sub: argparse.ArgumentParser) -> None:
        sub.add_argument(
            "--execute",
            action="store_true",
            help="really call the provider (creates and deletes rooms in the sandbox tenant)",
        )

    google = subparsers.add_parser(
        "google-create-delete",
        help="insert, replay, read, patch and delete a Google room; duplicate-name check",
        description=(
            f"Needs {ENV_GOOGLE_SA_JSON} (path to the service-account key file) and "
            f"{ENV_GOOGLE_ADMIN_EMAIL} (the admin the service account impersonates). "
            f"{ENV_GOOGLE_CUSTOMER} defaults to my_customer."
        ),
    )
    google.add_argument(
        "--building-id", help="building to put the room in (default: the first one listed)"
    )
    add_execute(google)

    for name, help_text in (
        ("ms-create-delete", "create, patch and delete a Microsoft room; mailbox check"),
        ("ms-description", "which Microsoft room property keeps free text"),
    ):
        sub = subparsers.add_parser(
            name,
            help=help_text,
            description=(
                f"Needs {ENV_MS_TENANT_ID}, {ENV_MS_CLIENT_ID} and {ENV_MS_CLIENT_SECRET} "
                "for an Entra app with Place.ReadWrite.All and Calendars.Read "
                "(application permissions, admin-consented)."
            ),
        )
        sub.add_argument("--floor-id", help=f"parent floor place id (or {ENV_MS_FLOOR_ID})")
        sub.add_argument(
            "--places-base",
            default=GRAPH_PLACES_DEFAULT_BASE,
            help="Graph base URL for /places calls (default: %(default)s)",
        )
        sub.add_argument("--poll-interval", type=float, default=10.0, help="seconds")
        sub.add_argument(
            "--provision-timeout",
            type=float,
            default=600.0,
            help="seconds to wait for the room email and mailbox",
        )
        sub.add_argument(
            "--post-delete-wait",
            type=float,
            default=60.0,
            help="seconds to wait after DELETE before checking the mailbox",
        )
        add_execute(sub)

    return parser


def _microsoft_options(args: argparse.Namespace, *, dry_run: bool) -> MicrosoftOptions:
    floor_id = args.floor_id or os.environ.get(ENV_MS_FLOOR_ID, "").strip()
    if not floor_id:
        if not dry_run:
            raise SpikeError(f"--floor-id (or {ENV_MS_FLOOR_ID}) is required with --execute")
        floor_id = "dry-run-floor-id"
    return MicrosoftOptions(
        floor_id=floor_id,
        places_base=args.places_base.rstrip("/"),
        poll_interval=args.poll_interval,
        provision_timeout=args.provision_timeout,
        post_delete_wait=args.post_delete_wait,
    )


def run(args: argparse.Namespace, transport: Transport | None = None) -> Findings:
    """Run the chosen subcommand and return its findings."""
    dry_run = not args.execute
    if transport is None:
        transport = DryRunTransport() if dry_run else UrllibTransport()

    if args.command == "google-create-delete":
        ctx = SpikeContext(
            transport=transport, token=google_access_token(dry_run=dry_run), dry_run=dry_run
        )
        customer = os.environ.get(ENV_GOOGLE_CUSTOMER, "").strip() or "my_customer"
        run_google_create_delete(ctx, customer=customer, building_id=args.building_id)
    else:
        options = _microsoft_options(args, dry_run=dry_run)
        ctx = SpikeContext(
            transport=transport,
            token=microsoft_access_token(transport, dry_run=dry_run),
            dry_run=dry_run,
        )
        if args.command == "ms-create-delete":
            run_ms_create_delete(ctx, options)
        else:
            run_ms_description(ctx, options)
    return {"command": args.command, "dry_run": dry_run, "findings": ctx.findings}


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point. Prints the findings as JSON on stdout; logs go to stderr."""
    args = build_parser().parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(message)s",
        stream=sys.stderr,
    )
    if not args.execute:
        logger.info("DRY RUN: no request leaves this machine. Pass --execute to call the provider.")
    try:
        summary = run(args)
    except SpikeError as exc:
        logger.error("spike stopped: %s", exc)
        return 1
    sys.stdout.write(json.dumps(summary, indent=2, sort_keys=True) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())

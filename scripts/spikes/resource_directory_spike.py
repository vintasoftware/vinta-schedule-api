def microsoft_access_token(transport: Transport, *, dry_run: bool) -> str:
    """App-only token through the client-credentials flow, the way Phase 5 will get it."""
    if dry_run:
        logger.info("[dry-run] would request a Microsoft app-only token")
        return DRY_RUN_TOKEN
    tenant_id = _require_env(ENV_MS_TENANT_ID)
    response = transport.send(
        "microsoft.token",
        "POST",
        f"{MS_LOGIN_BASE}/{urllib.parse.quote(tenant_id)}/oauth2/v2.0/token",
        form_body={
            "grant_type": "client_credentials",
            "client_id": _require_env(ENV_MS_CLIENT_ID),
            "client_secret": _require_env(ENV_MS_CLIENT_SECRET),
            "scope": MS_GRAPH_DEFAULT_SCOPE,
        },
    )
    token = response.body.get("access_token")
    if not response.ok or not isinstance(token, str):
        raise SpikeError(
            f"token request failed with HTTP {response.status} ({provider_error_code(response)})"
        )
    return token


@dataclasses.dataclass(frozen=True)
class MicrosoftOptions:
    """Where and how patiently to run the Microsoft scenarios."""

    floor_id: str
    places_base: str
    poll_interval: float
    provision_timeout: float
    post_delete_wait: float


def _place_url(options: MicrosoftOptions, place_id: str | None = None) -> str:
    base = f"{options.places_base}/places"
    return base if place_id is None else f"{base}/{urllib.parse.quote(place_id)}"


def _create_ms_room(
    ctx: SpikeContext,
    options: MicrosoftOptions,
    label: str,
    tag: str,
    cleanups: Cleanups,
) -> tuple[str, float]:
    """POST a room under the floor. Returns its place id and the monotonic create time."""
    started = ctx.monotonic()
    created = ctx.send(
        f"microsoft.places.create({label})",
        "POST",
        _place_url(options),
        {
            "@odata.type": "microsoft.graph.room",
            "displayName": f"Vinta spike {label}",
            "parentId": options.floor_id,
            "capacity": 4,
            "tags": [tag],
        },
    )
    ctx.record("create_status", created.status)
    if not created.ok:
        ctx.record("create_error", provider_error_code(created))
        raise SpikeError(f"create failed with HTTP {created.status}; nothing else to test")
    place_id = created.body.get("id")
    if not isinstance(place_id, str):
        raise SpikeError("create returned no place id")
    ctx.record("place_id", place_id)
    created_email = created.body.get("emailAddress")
    ctx.record("create_response_has_email", bool(created_email))
    cleanups[place_id] = lambda: ctx.send(
        f"microsoft.places.delete({place_id})", "DELETE", _place_url(options, place_id)
    )
    return place_id, started


def _poll(
    ctx: SpikeContext,
    options: MicrosoftOptions,
    check: Callable[[], HttpResponse],
    done: Callable[[HttpResponse], bool],
) -> HttpResponse:
    """Call `check` until `done` says so or the provisioning timeout runs out."""
    deadline = ctx.monotonic() + options.provision_timeout
    while True:
        response = check()
        if done(response) or ctx.monotonic() >= deadline:
            return response
        ctx.wait(options.poll_interval)


def run_ms_create_delete(ctx: SpikeContext, options: MicrosoftOptions) -> None:
    """Spec open question 1, plus the tag-lookup idempotency assumption of Phase 6."""
    label = _spike_label()
    tag = f"vinta-link-{uuid.uuid4()}"
    ctx.record("token_roles", jwt_roles(ctx.token))
    cleanups: Cleanups = {}

    with _cleanup_on_exit(cleanups):
        place_id, created_at = _create_ms_room(ctx, options, label, tag, cleanups)

        # Provisioning: when does the place report a mailbox address?
        place = _poll(
            ctx,
            options,
            lambda: ctx.send(
                f"microsoft.places.get({place_id})", "GET", _place_url(options, place_id)
            ),
            lambda r: r.ok and bool(r.body.get("emailAddress")),
        )
        email = place.body.get("emailAddress")
        ctx.record(
            "email_address_seconds", round(ctx.monotonic() - created_at, 1) if email else None
        )
        ctx.record("email_address_hash", opaque(email) if email else None)
        tags = place.body.get("tags")
        ctx.record("tag_round_trip", isinstance(tags, list) and tag in tags)

        # Phase 6 looks up the tag before any POST, so the lookup itself must work.
        tag_filter = urllib.parse.quote(f"tags/any(t:t eq '{tag}')")
        lookup = ctx.send(
            "microsoft.places.list(rooms, filter by tag)",
            "GET",
            f"{options.places_base}/places/microsoft.graph.room?$filter={tag_filter}",
        )
        matches = lookup.body.get("value")
        ctx.record("tag_filter_status", lookup.status)
        ctx.record("tag_filter_error", provider_error_code(lookup))
        ctx.record(
            "tag_filter_found_room",
            isinstance(matches, list)
            and any(isinstance(m, dict) and m.get("id") == place_id for m in matches),
        )

        if email:
            mailbox_url = f"{GRAPH_V1_BASE}/users/{urllib.parse.quote(email)}"
            calendar = _poll(
                ctx,
                options,
                lambda: ctx.send(
                    "microsoft.mailbox.calendar(room)", "GET", f"{mailbox_url}/calendar"
                ),
                lambda r: r.ok,
            )
            ctx.record("mailbox_calendar_status", calendar.status)
            ctx.record(
                "mailbox_calendar_seconds",
                round(ctx.monotonic() - created_at, 1) if calendar.ok else None,
            )
            # Plan open question 4: is Calendars.Read enough for app-only getSchedule?
            schedule = ctx.send(
                "microsoft.getSchedule(room)",
                "POST",
                f"{mailbox_url}/calendar/getSchedule",
                {
                    "schedules": [email],
                    "startTime": {"dateTime": "2030-01-01T09:00:00", "timeZone": "UTC"},
                    "endTime": {"dateTime": "2030-01-01T10:00:00", "timeZone": "UTC"},
                },
            )
            ctx.record("get_schedule_status", schedule.status)
            ctx.record("get_schedule_error", provider_error_code(schedule))

        patched = ctx.send(
            f"microsoft.places.patch({place_id}, capacity)",
            "PATCH",
            _place_url(options, place_id),
            {"@odata.type": "microsoft.graph.room", "capacity": 8},
        )
        ctx.record("patch_capacity_status", patched.status)
        ctx.record("patch_capacity_error", provider_error_code(patched))
        after_patch = ctx.send(
            f"microsoft.places.get({place_id}, after patch)", "GET", _place_url(options, place_id)
        )
        ctx.record("patch_capacity_round_trip", after_patch.body.get("capacity") == 8)
        after_tags = after_patch.body.get("tags")
        ctx.record("tag_survives_patch", isinstance(after_tags, list) and tag in after_tags)

        deleted = _delete_now(cleanups, place_id)
        ctx.record("delete_status", deleted.status)
        ctx.record("delete_error", provider_error_code(deleted))
        after_delete = ctx.send(
            f"microsoft.places.get({place_id}, after delete)", "GET", _place_url(options, place_id)
        )
        ctx.record("get_place_after_delete_status", after_delete.status)

        # Q1: does the room mailbox outlive the place?
        if email:
            ctx.wait(options.post_delete_wait)
            mailbox_url = f"{GRAPH_V1_BASE}/users/{urllib.parse.quote(email)}"
            user = ctx.send(
                "microsoft.users.get(room, after delete)", "GET", f"{mailbox_url}?$select=id"
            )
            ctx.record("mailbox_user_status_after_delete", user.status)
            ctx.record("mailbox_user_error_after_delete", provider_error_code(user))
            calendar_after = ctx.send(
                "microsoft.mailbox.calendar(room, after delete)", "GET", f"{mailbox_url}/calendar"
            )
            ctx.record("mailbox_calendar_status_after_delete", calendar_after.status)


def run_ms_description(ctx: SpikeContext, options: MicrosoftOptions) -> None:
    """Spec open question 2: which room property, if any, keeps free text."""
    label = _spike_label()
    tag = f"vinta-link-{uuid.uuid4()}"
    cleanups: Cleanups = {}
    # Free text as a partner would send it: long, punctuated, multi-line.
    marker = f"Vinta spike {label}. Second line, with punctuation: ok?\n" + "x" * 240

    with _cleanup_on_exit(cleanups):
        place_id, _ = _create_ms_room(ctx, options, label, tag, cleanups)
        place = _poll(
            ctx,
            options,
            lambda: ctx.send(
                f"microsoft.places.get({place_id})", "GET", _place_url(options, place_id)
            ),
            lambda r: r.ok,
        )
        ctx.record(
            "room_property_names",
            sorted(key for key in place.body if not key.startswith("@odata")),
        )

        for field in MS_DESCRIPTION_CANDIDATES:
            patched = ctx.send(
                f"microsoft.places.patch({place_id}, {field})",
                "PATCH",
                _place_url(options, place_id),
                {"@odata.type": "microsoft.graph.room", field: marker},
            )
            readback = ctx.send(
                f"microsoft.places.get({place_id}, after {field})",
                "GET",
                _place_url(options, place_id),
            )
            stored = readback.body.get(field)
            ctx.record(
                f"candidate_{field}",
                {
                    "patch_status": patched.status,
                    "patch_error": provider_error_code(patched),
                    "round_trip_exact": stored == marker,
                    "stored_length": len(stored) if isinstance(stored, str) else None,
                    "sent_length": len(marker),
                },
            )



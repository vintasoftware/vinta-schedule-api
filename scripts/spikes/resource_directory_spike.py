class SpikeError(Exception):
    """The spike could not run (bad configuration or a failed prerequisite step)."""


@dataclasses.dataclass(frozen=True)
class HttpResponse:
    """The parts of a provider response the spike looks at."""

    status: int
    body: dict[str, Any]

    @property
    def ok(self) -> bool:
        """Whether the status is 2xx."""
        return 200 <= self.status < 300


class Transport(Protocol):
    """Sends one HTTP request. `operation` is a log label, never the URL."""

    def send(
        self,
        operation: str,
        method: str,
        url: str,
        *,
        headers: dict[str, str] | None = None,
        json_body: dict[str, Any] | None = None,
        form_body: dict[str, str] | None = None,
    ) -> HttpResponse:
        """Send the request and return the response, including 4xx/5xx ones."""
        ...


class UrllibTransport:
    """Real HTTP, through the standard library so the spike adds no dependency."""

    def __init__(self, timeout_seconds: float = 30.0) -> None:
        self.timeout_seconds = timeout_seconds

    def send(
        self,
        operation: str,
        method: str,
        url: str,
        *,
        headers: dict[str, str] | None = None,
        json_body: dict[str, Any] | None = None,
        form_body: dict[str, str] | None = None,
    ) -> HttpResponse:
        """Send the request. HTTP errors come back as a response, not an exception."""
        if not url.startswith("https://"):
            raise SpikeError(f"refusing non-HTTPS request for {operation}")
        request_headers = {"Accept": "application/json", **(headers or {})}
        data: bytes | None = None
        if json_body is not None:
            data = json.dumps(json_body).encode()
            request_headers["Content-Type"] = "application/json"
        elif form_body is not None:
            data = urllib.parse.urlencode(form_body).encode()
            request_headers["Content-Type"] = "application/x-www-form-urlencoded"
        request = urllib.request.Request(  # noqa: S310 - scheme checked above
            url, data=data, method=method, headers=request_headers
        )
        try:
            with urllib.request.urlopen(  # noqa: S310 - scheme checked above
                request, timeout=self.timeout_seconds
            ) as raw_response:
                status = raw_response.status
                raw = raw_response.read()
        except urllib.error.HTTPError as exc:
            status = exc.code
            raw = exc.read()
        response = HttpResponse(status=status, body=_parse_json_object(raw))
        logger.info("%s %s -> HTTP %s", method, operation, status)
        return response


class DryRunTransport:
    """Logs each request it would send and answers with a canned success.

    The canned body carries every key the scenarios read, so a dry run walks the whole
    scenario and shows every call it would make, in order.
    """

    CANNED_BODY: dict[str, Any] = {  # noqa: RUF012 - copied before being returned
        "id": "dry-run-place-id",
        "resourceId": "dry-run-resource-id",
        "resourceEmail": "dry-run-room@example.invalid",
        "emailAddress": "dry-run-room@example.invalid",
        "capacity": 8,
        "tags": [],
        "buildings": [{"buildingId": "dry-run-building-id"}],
        "value": [],
    }

    def __init__(self) -> None:
        self.calls: list[tuple[str, str]] = []

    def send(
        self,
        operation: str,
        method: str,
        url: str,
        *,
        headers: dict[str, str] | None = None,
        json_body: dict[str, Any] | None = None,
        form_body: dict[str, str] | None = None,
    ) -> HttpResponse:
        """Record the call and return a canned 2xx response."""
        self.calls.append((method, operation))
        logger.info("[dry-run] would send %s %s", method, operation)
        status = 204 if method == "DELETE" else 200
        return HttpResponse(status=status, body=json.loads(json.dumps(self.CANNED_BODY)))


@dataclasses.dataclass
class SpikeContext:
    """What every scenario needs: how to send, how to wait, where to write findings."""

    transport: Transport
    token: str
    dry_run: bool
    sleep: Callable[[float], None] = time.sleep
    monotonic: Callable[[], float] = time.monotonic
    findings: Findings = dataclasses.field(default_factory=dict)

    def auth_headers(self) -> dict[str, str]:
        """Bearer header for the provider API."""
        return {"Authorization": f"Bearer {self.token}"}

    def send(
        self, operation: str, method: str, url: str, json_body: dict[str, Any] | None = None
    ) -> HttpResponse:
        """Send an authenticated JSON request."""
        return self.transport.send(
            operation, method, url, headers=self.auth_headers(), json_body=json_body
        )

    def wait(self, seconds: float) -> None:
        """Sleep, except in a dry run, where there is nothing to wait for."""
        if self.dry_run:
            logger.info("[dry-run] would wait %ss", seconds)
            return
        self.sleep(seconds)

    def record(self, key: str, value: Any) -> None:
        """Store one finding and log it. Callers pass only safe values."""
        self.findings[key] = value
        logger.info("finding %s = %s", key, value)



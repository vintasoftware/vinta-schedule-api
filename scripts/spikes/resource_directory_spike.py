#!/usr/bin/env python
"""Spike: what the Google and Microsoft room directories do when we write to them.

Answers spec open questions 1, 2 and 8 of
`ai-plans/2026-10-04-RESOURCE_CALENDAR_PROVIDER_SYNC_SPEC.md` against **sandbox**
tenants. How to run it, and the table to record the answers in, are in
`docs/integrations/resource-directory-spike.md`.

Subcommands:

* `google-create-delete` -- Google Admin SDK Directory: insert a room with a
  client-chosen `resourceId`, replay the insert, read it back, patch capacity, delete
  it. Also checks whether `buildingId` is required for `CONFERENCE_ROOM` and whether a
  duplicate name is rejected.
* `ms-create-delete` -- Microsoft Graph Places: create a room under a floor, time the
  mailbox provisioning, check that a tag round-trips and can be searched, PATCH,
  DELETE, then check whether the room mailbox is still there.
* `ms-description` -- Microsoft Graph Places: list the room's property names and
  check which candidate property keeps a free-text value.

Safety contract:

* **Dry-run by default.** Without `--execute` the script makes no network call at
  all: tokens are fake and every request is logged and answered by a canned response.
* Credentials come only from environment variables (see `--help` of each subcommand).
* Logs and the final JSON summary hold only opaque ids, HTTP status codes, provider
  error codes, timings and property *names*. Room emails are hashed. Room names and
  descriptions are generated by the script and are never logged.
* Every room the script creates is deleted in a `finally` block, even when a step
  fails.

Standalone on purpose: no Django import, so it runs with `uv run python` and no `.env`.
"""


def google_access_token(*, dry_run: bool) -> str:
    """Mint a domain-wide-delegation token with the directory **write** scope."""
    if dry_run:
        logger.info("[dry-run] would mint a Google service-account token (write scope)")
        return DRY_RUN_TOKEN
    # Imported lazily: a dry run must not even load the HTTP transport.
    from google.auth.transport.requests import Request
    from google.oauth2 import service_account

    key_path = _require_env(ENV_GOOGLE_SA_JSON)
    admin_email = _require_env(ENV_GOOGLE_ADMIN_EMAIL)
    credentials = service_account.Credentials.from_service_account_file(
        key_path, scopes=[GOOGLE_WRITE_SCOPE]
    ).with_subject(admin_email)
    credentials.refresh(Request())
    token = credentials.token
    if not token:
        raise SpikeError("Google returned no access token")
    return str(token)


def _google_calendars_url(customer: str, resource_id: str | None = None) -> str:
    base = f"{GOOGLE_DIRECTORY_BASE}/customer/{urllib.parse.quote(customer)}/resources/calendars"
    if resource_id is None:
        return base
    return f"{base}/{urllib.parse.quote(resource_id)}"


def _google_room_body(
    resource_id: str, name: str, building_id: str | None, capacity: int
) -> dict[str, Any]:
    body: dict[str, Any] = {
        "resourceId": resource_id,
        "resourceName": name,
        "resourceCategory": "CONFERENCE_ROOM",
        "capacity": capacity,
        "resourceDescription": f"Vinta spike room {resource_id}",
    }
    if building_id is not None:
        body["buildingId"] = building_id
        body["floorName"] = "1"
    return body


def run_google_create_delete(ctx: SpikeContext, *, customer: str, building_id: str | None) -> None:
    """Spec open question 8, plus the idempotent-insert assumption of Phase 4."""
    label = _spike_label()
    cleanups: Cleanups = {}

    def schedule_delete(resource_id: str) -> None:
        cleanups[resource_id] = lambda: ctx.send(
            f"google.delete({resource_id})", "DELETE", _google_calendars_url(customer, resource_id)
        )

    with _cleanup_on_exit(cleanups):
        if building_id is None:
            buildings = ctx.send(
                "google.buildings.list",
                "GET",
                f"{GOOGLE_DIRECTORY_BASE}/customer/{urllib.parse.quote(customer)}"
                "/resources/buildings?maxResults=1",
            )
            listed = buildings.body.get("buildings") or []
            if not buildings.ok or not listed:
                raise SpikeError(
                    f"could not find a building (HTTP {buildings.status}); pass --building-id"
                )
            building_id = str(listed[0]["buildingId"])
        ctx.record("building_id", building_id)

        # Q8a: is buildingId required for CONFERENCE_ROOM?
        no_building_id = f"vinta-spike-{label}-nobuilding"
        no_building = ctx.send(
            f"google.insert({no_building_id}, no building)",
            "POST",
            _google_calendars_url(customer),
            _google_room_body(no_building_id, f"Vinta spike {label} nb", None, 4),
        )
        if no_building.ok:
            schedule_delete(no_building_id)
        ctx.record("insert_without_building_status", no_building.status)
        ctx.record("insert_without_building_error", provider_error_code(no_building))

        # The resourceId Phase 4 sets deterministically to `vinta-<link uuid>`.
        resource_id = f"vinta-spike-{label}"
        room_name = f"Vinta spike {label}"
        body = _google_room_body(resource_id, room_name, building_id, 4)
        inserted = ctx.send(
            f"google.insert({resource_id})", "POST", _google_calendars_url(customer), body
        )
        ctx.record("insert_status", inserted.status)
        if not inserted.ok:
            ctx.record("insert_error", provider_error_code(inserted))
            raise SpikeError(f"insert failed with HTTP {inserted.status}; nothing else to test")
        schedule_delete(resource_id)
        ctx.record("insert_kept_client_resource_id", inserted.body.get("resourceId") == resource_id)

        # Replaying the same insert: Phase 4 treats a 409 as "already created".
        replay = ctx.send(
            f"google.insert({resource_id}, replay)", "POST", _google_calendars_url(customer), body
        )
        ctx.record("replay_insert_status", replay.status)
        ctx.record("replay_insert_error", provider_error_code(replay))

        readback = ctx.send(
            f"google.get({resource_id})", "GET", _google_calendars_url(customer, resource_id)
        )
        ctx.record("readback_status", readback.status)
        email = readback.body.get("resourceEmail")
        ctx.record("readback_resource_email_hash", opaque(email) if email else None)
        ctx.record(
            "readback_description_round_trip",
            readback.body.get("resourceDescription") == body["resourceDescription"],
        )

        patched = ctx.send(
            f"google.patch({resource_id}, capacity)",
            "PATCH",
            _google_calendars_url(customer, resource_id),
            {"capacity": 8},
        )
        ctx.record("patch_capacity_status", patched.status)
        after_patch = ctx.send(
            f"google.get({resource_id}, after patch)",
            "GET",
            _google_calendars_url(customer, resource_id),
        )
        ctx.record("patch_capacity_round_trip", after_patch.body.get("capacity") == 8)

        # Q8b: does the directory reject a second room with the same name?
        duplicate_id = f"vinta-spike-{label}-dup"
        duplicate = ctx.send(
            f"google.insert({duplicate_id}, duplicate name)",
            "POST",
            _google_calendars_url(customer),
            _google_room_body(duplicate_id, room_name, building_id, 4),
        )
        if duplicate.ok:
            schedule_delete(duplicate_id)
        ctx.record("duplicate_name_insert_status", duplicate.status)
        ctx.record("duplicate_name_insert_error", provider_error_code(duplicate))

        deleted = _delete_now(cleanups, resource_id)
        ctx.record("delete_status", deleted.status)
        after_delete = ctx.send(
            f"google.get({resource_id}, after delete)",
            "GET",
            _google_calendars_url(customer, resource_id),
        )
        ctx.record("get_after_delete_status", after_delete.status)



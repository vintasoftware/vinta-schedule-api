def _parse_json_object(raw: bytes) -> dict[str, Any]:
    if not raw:
        return {}
    try:
        parsed = json.loads(raw)
    except ValueError:
        return {}
    return parsed if isinstance(parsed, dict) else {"value": parsed}


def opaque(value: str) -> str:
    """A short stable hash, so a value can be compared across runs without being shown."""
    return hashlib.sha256(value.encode()).hexdigest()[:12]


def provider_error_code(response: HttpResponse) -> str | None:
    """The provider's machine-readable error code, never its human message.

    Error messages can echo request values back, so they stay out of logs and findings.
    """
    error = response.body.get("error")
    if not isinstance(error, dict):
        return None
    # Google: {"error": {"code": 409, "errors": [{"reason": "duplicate"}], "status": ...}}
    errors = error.get("errors")
    if isinstance(errors, list) and errors and isinstance(errors[0], dict):
        reason = errors[0].get("reason")
        if isinstance(reason, str):
            return reason
    # Google `status` or Microsoft `code`.
    for key in ("status", "code"):
        code = error.get(key)
        if isinstance(code, str):
            return code
    return None


def jwt_roles(token: str) -> list[str]:
    """The `roles` claim of an app-only access token (the granted application permissions).

    The signature is not checked: the token came straight from the token endpoint and
    only its claims are reported.
    """
    parts = token.split(".")
    if len(parts) < 2:
        return []
    payload = parts[1] + "=" * (-len(parts[1]) % 4)
    try:
        claims = json.loads(base64.urlsafe_b64decode(payload))
    except ValueError:
        return []
    roles = claims.get("roles", []) if isinstance(claims, dict) else []
    return sorted(role for role in roles if isinstance(role, str))


def _require_env(name: str) -> str:
    value = os.environ.get(name, "").strip()
    if not value:
        raise SpikeError(f"environment variable {name} is required with --execute")
    return value


def _spike_label() -> str:
    return uuid.uuid4().hex[:12]


def _delete_now(cleanups: Cleanups, label: str) -> HttpResponse:
    """Run one registered cleanup as a scenario step.

    It stays registered unless it worked, so a delete that fails or raises is tried
    again on the way out, and logged there if it fails again.
    """
    response = cleanups[label]()
    if response.ok or response.status == 404:
        del cleanups[label]
    return response


@contextmanager
def _cleanup_on_exit(cleanups: Cleanups) -> Iterator[None]:
    """Run every pending cleanup, newest first, whatever happened in the block."""
    try:
        yield
    finally:
        while cleanups:
            label, cleanup = cleanups.popitem()
            try:
                response = cleanup()
            except Exception:
                logger.exception("cleanup %s raised; delete it by hand", label)
                continue
            if not response.ok and response.status != 404:
                logger.error(
                    "cleanup %s returned HTTP %s; delete it by hand", label, response.status
                )



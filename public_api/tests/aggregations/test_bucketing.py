"""Temporal bucketing against real rows — the load-bearing test of this phase.

Every assertion here is about the same question: whose day is it? The rows store
a local wall clock plus their own IANA name, and the aggregate cuts buckets on a
clock the caller names, so the same four events land in different buckets
depending on the timezone the query asked for. If that is wrong nothing raises —
the numbers are just quietly attributed to the wrong days.
"""

import datetime
from zoneinfo import ZoneInfo

from django.db import connection
from django.test.utils import CaptureQueriesContext

import pytest
from model_bakery import baker

from calendar_integration.constants import CalendarProvider
from calendar_integration.models import Calendar, CalendarEvent
from common.organization_context import organization_context
from organizations.models import Organization
from public_api.aggregations.dimensions import (
    CalendarEventGroupByInput,
    CalendarEventTemporalGroupBy,
    CalendarEventTemporalGroupByField,
    resolve_group_by_inputs,
)
from public_api.aggregations.executor import execute_aggregate_plan
from public_api.aggregations.plan import AggregatableEntity, AggregateOp, AggregateQueryPlan
from public_api.aggregations.registry import build_metric
from public_api.aggregations.types import TemporalGranularity


SAO_PAULO = ZoneInfo("America/Sao_Paulo")
NEW_YORK = ZoneInfo("America/New_York")
UTC = ZoneInfo("UTC")

EVENT = AggregatableEntity.CALENDAR_EVENT


def _make_event(
    organization: Organization,
    calendar: Calendar,
    *,
    external_id: str,
    utc_start: datetime.datetime,
    minutes: int = 30,
) -> CalendarEvent:
    """Create an event whose ``start_time`` is exactly ``utc_start``.

    ``start_time`` is generated by ``convert_naive_utc_to_timezone`` over the
    naive column and the row's own IANA name, so storing the naive value with
    ``timezone="UTC"`` pins the instant. The row's own timezone is deliberately
    not the one the aggregate buckets in — that separation is the whole point.
    """
    return baker.make(
        CalendarEvent,
        organization=organization,
        calendar=calendar,
        external_id=external_id,
        title=external_id,
        timezone="UTC",
        start_time_tz_unaware=utc_start,
        end_time_tz_unaware=utc_start + datetime.timedelta(minutes=minutes),
    )


def _bucket_plan(
    field: CalendarEventTemporalGroupByField,
    granularity: TemporalGranularity,
    tzinfo: ZoneInfo,
) -> AggregateQueryPlan:
    resolved = resolve_group_by_inputs(
        EVENT,
        [
            CalendarEventGroupByInput(
                temporal=CalendarEventTemporalGroupBy(field=field, granularity=granularity)
            )
        ],
        tzinfo,
    )
    return AggregateQueryPlan(
        entity=EVENT,
        dimensions=tuple(one.dimension for one in resolved),
        metrics=(build_metric(EVENT, "count", AggregateOp.COUNT, alias="count"),),
    )


def _day_counts(organization: Organization, tzinfo: ZoneInfo) -> dict[datetime.datetime, int]:
    plan = _bucket_plan(
        CalendarEventTemporalGroupByField.START_TIME, TemporalGranularity.DAY, tzinfo
    )
    with organization_context(organization):
        rows = execute_aggregate_plan(plan, CalendarEvent.objects.all())
    return {row["start_time_day"]: row["count"] for row in rows}



"""Move every billing row from ``payments_*`` to ``vinta_billing_*``, move the
``manage_billing`` grant with it, and drop this app's twenty models.

**Copy forward, then drop -- not ``AlterModelTable``.** A rename would have to be
ordered either before ``vinta_billing.0001_initial`` (which then needs
``migrate --fake-initial`` at deploy time, and ``pytest-django`` builds the test
database with a plain ``migrate``) or after it (which means dropping the tables
that migration just created and inheriting ``payments_``-prefixed index and
constraint names that later package migrations would fail to find). The copy
runs unattended in every environment and leaves the package's own names in
place. Its cost is a table copy, acceptable at this project's volume and worth
revisiting at a much larger one. See the implementation plan's *Risk & Rollout
Notes*.

**Explicit column lists, never ``SELECT *``.** The two tables carry identical
column *sets* but not identical column *orders* -- ``billingprofile`` alone has
``billing_address_id`` and ``payment_provider`` transposed between them, and
``subscription`` differs in five positions -- so ``INSERT ... SELECT *`` would
write plausible-looking values into the wrong columns. ``_assert_columns_match``
additionally re-derives both tables' real column sets from
``information_schema`` and refuses to copy if either disagrees with the list
below, so a future package release that adds a column fails loudly here instead
of silently dropping it.

**Sequences.** Every table except ``billingprofile`` (whose primary key is its
``organization_id``) has a ``bigint GENERATED BY DEFAULT AS IDENTITY`` ``id``.
Copying rows with their primary keys does not move the identity sequence, so the
very next insert would collide on a key that already exists -- a failure that
surfaces long after this migration reports success. Each copy is therefore
followed by a ``setval`` on the *destination* table's own sequence, looked up
with ``pg_get_serial_sequence`` rather than spelled as a literal.

**Reverse.** ``migrate payments 0022`` is this plan's rollback lever, and it is a
real one. Django unapplies, in order: this migration (the deletions reverse into
``CREATE TABLE``s Django derives from the migration state, then the rows are
copied back and ``vinta_billing_*`` is emptied), then ``vinta_billing.0002`` and
``0001`` -- forced by ``0023``'s ``run_before`` edge, and necessary, because
``0023``'s own reverse re-adds the thirteen constraint and index names the
package's tables would otherwise still be holding -- then ``0023`` itself. What
comes back is the schema and the data as ``payments.0022`` left them.

One asymmetry worth stating: ``vinta_billing.manage_billing`` is deleted on the
way back, but Django's ``post_migrate`` ``create_permissions`` recreates it,
unassigned, at the end of the same command. That is the correct end state -- the
permission belongs to a model that still exists, and what the rollback actually
has to undo is the *grant*, which is revoked here and stays revoked.
"""


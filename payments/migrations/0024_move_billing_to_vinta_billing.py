def _assert_columns_match(cursor, table: str, columns: tuple[str, ...]) -> None:
    """Refuse to copy a table whose real columns are not the ones declared here.

    A column present in both tables but missing from ``TABLES`` would be dropped
    silently -- the ``INSERT`` would succeed and the values would simply not
    arrive. That is the one failure mode an explicit column list does not catch
    on its own, so it is caught here instead.
    """
    cursor.execute(
        "SELECT column_name FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = %s",
        [table],
    )
    actual = {row[0] for row in cursor.fetchall()}
    if actual != set(columns):
        raise RuntimeError(
            f"{table} does not have the columns this migration was written against. "
            f"Missing from the table: {sorted(set(columns) - actual)}. "
            f"Present but not copied: {sorted(actual - set(columns))}."
        )


def _copy(cursor, source: str, destination: str, columns: tuple[str, ...]) -> None:
    _assert_columns_match(cursor, source, columns)
    _assert_columns_match(cursor, destination, columns)
    column_list = ", ".join(f'"{column}"' for column in columns)
    cursor.execute(
        f'INSERT INTO "{destination}" ({column_list}) SELECT {column_list} FROM "{source}"'  # noqa: S608
    )


def _advance_sequence(cursor, table: str, columns: tuple[str, ...]) -> None:
    """Point ``table``'s identity sequence past the highest primary key copied in.

    ``is_called=False`` with ``max(id) + 1`` rather than ``is_called=True`` with
    ``max(id)`` so an empty table lands on 1 -- ``setval`` rejects 0, which is
    below the sequence's minimum.
    """
    if "id" not in columns:
        # ``billingprofile``: its primary key is ``organization_id``, supplied by
        # the caller, so there is no sequence to advance.
        return
    cursor.execute(
        f'SELECT setval(pg_get_serial_sequence(%s, \'id\'), '  # noqa: S608
        f'COALESCE((SELECT MAX("id") FROM "{table}"), 0) + 1, false)',
        [table],
    )


def copy_rows_into_vinta_billing(apps, schema_editor):
    with schema_editor.connection.cursor() as cursor:
        for table, columns in TABLES:
            _copy(cursor, f"{OLD_PREFIX}{table}", f"{NEW_PREFIX}{table}", columns)
            _advance_sequence(cursor, f"{NEW_PREFIX}{table}", columns)


def copy_rows_back_into_payments(apps, schema_editor):
    """Put the rows back where ``0022`` left them, and leave ``vinta_billing_*``
    as ``vinta_billing.0002`` left it: created and empty.

    Emptying the destination is what makes this a true inverse rather than a
    one-way copy: without it, re-applying this migration would collide on every
    primary key it had already moved once.
    """
    with schema_editor.connection.cursor() as cursor:
        for table, columns in TABLES:
            _copy(cursor, f"{NEW_PREFIX}{table}", f"{OLD_PREFIX}{table}", columns)
            _advance_sequence(cursor, f"{OLD_PREFIX}{table}", columns)
        # Children before parents, so no foreign key is ever left dangling.
        for table, columns in reversed(TABLES):
            cursor.execute(f'DELETE FROM "{NEW_PREFIX}{table}"')  # noqa: S608
            _advance_sequence(cursor, f"{NEW_PREFIX}{table}", columns)


def _content_type_and_permission(apps, db_alias, app_label: str):
    ContentType = apps.get_model("contenttypes", "ContentType")
    Permission = apps.get_model("auth", "Permission")
    content_type, _ = ContentType.objects.using(db_alias).get_or_create(
        app_label=app_label, model="subscription"
    )
    permission, _ = Permission.objects.using(db_alias).get_or_create(
        content_type=content_type,
        codename=MANAGE_BILLING_CODENAME,
        defaults={"name": MANAGE_BILLING_NAME},
    )
    return content_type, permission


def _move_manage_billing(apps, schema_editor, *, to_app_label: str, from_app_label: str):
    """Re-grant ``manage_billing`` on ``to_app_label``'s subscription content type,
    then revoke and delete the one on ``from_app_label``'s.

    The permission row is created here rather than left to ``post_migrate``:
    ``create_permissions`` runs at the *end* of the ``migrate`` command, long
    after this, so on a fresh database ``vinta_billing.manage_billing`` does not
    exist yet at this point. ``get_or_create`` covers the already-migrated case.

    Deleting the ``Permission`` row is what revokes it -- the ``Group`` /
    ``Permission`` many-to-many rows go with it -- so the grant cannot survive
    on a content type that no longer describes anything.
    """
    Group = apps.get_model("auth", "Group")
    ContentType = apps.get_model("contenttypes", "ContentType")
    Permission = apps.get_model("auth", "Permission")
    db_alias = schema_editor.connection.alias

    _, permission = _content_type_and_permission(apps, db_alias, to_app_label)
    for group_name in GROUPS_HOLDING_MANAGE_BILLING:
        group = Group.objects.using(db_alias).filter(name=group_name).first()
        if group is not None:
            # ``add``, not ``set``: additive and idempotent, and it leaves any
            # grant an operator made deliberately alone. Same convention as
            # ``organizations.0028``, which is where these groups come from.
            group.permissions.add(permission)

    stale = (
        ContentType.objects.using(db_alias)
        .filter(app_label=from_app_label, model="subscription")
        .first()
    )
    if stale is not None:
        Permission.objects.using(db_alias).filter(content_type=stale).delete()
        stale.delete()


def grant_on_vinta_billing(apps, schema_editor):
    _move_manage_billing(
        apps, schema_editor, to_app_label="vinta_billing", from_app_label="payments"
    )


def grant_on_payments(apps, schema_editor):
    _move_manage_billing(
        apps, schema_editor, to_app_label="payments", from_app_label="vinta_billing"
    )


